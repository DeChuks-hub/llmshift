"""Reports, pull request comments and issues say what wrote them, with a link, so that the
people who read them (a whole team, on a pull request) can find the tool."""

from __future__ import annotations

from llmshift import __version__
from llmshift.compare import run_compare
from llmshift.textutil import PROJECT_URL, credit


def test_the_credit_line_links_to_the_project():
    assert credit() == f"<sub>Generated by [llmshift]({PROJECT_URL}) {__version__}</sub>"
    assert credit("Sent by").startswith("<sub>Sent by [llmshift](https://github.com/DeChuks-hub/llmshift) ")


def test_markdown_reports_end_with_it(make_case):
    from llmshift.pick import pick_markdown, run_pick
    from llmshift.report import compare_html, compare_markdown

    cases = [make_case(f"q{i}", user=f"q{i}", id=f"c{i}", checks=[{"type": "contains", "value": "q"}]) for i in range(2)]
    result = run_compare(cases, "mock:echo", show_progress=False, min_pass_rate=0.95)
    assert compare_markdown(result).rstrip().endswith(credit())
    assert f'Generated by <a href="{PROJECT_URL}">llmshift</a>' in compare_html(result)
    assert pick_markdown(run_pick(cases, ["mock:echo"], min_pass_rate=0.95)).rstrip().endswith(credit())


def test_the_pull_request_comment_of_check_ends_with_it():
    from llmshift.prcheck import CheckRun, check_markdown

    assert check_markdown(CheckRun(model="mock:legacy", base="main")).rstrip().endswith(credit())
